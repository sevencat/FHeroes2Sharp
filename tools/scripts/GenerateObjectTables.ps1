<#
.SYNOPSIS
    Regenerates src/FHeroes2.Game/Maps/MapObjectCatalog.Roads.cs.

.DESCRIPTION
    The road table of the reference (fheroes2, src/fheroes2/maps/map_object_info.cpp, populateRoads)
    is 512 direction layouts plus the castle entrance road, spelled out one emplace_back per part and
    one copy assignment per mirrored layout. Retyping about 640 lines by hand is not an option, so
    this script extracts them from the C++ source and emits C# with the same order and the same
    statements.

    Every source line must be recognised; an unknown statement stops the script instead of being
    skipped, so a change in the reference cannot silently produce a shorter table.

    The generated file is checked in: building the port does not need the reference checkout. Run the
    script after updating that checkout, then run MapObjectCatalogTests, which pins the size of the
    table and a few entries.

.EXAMPLE
    pwsh tools/scripts/GenerateObjectTables.ps1
#>
param(
    [Parameter(Mandatory = $false)]
    [string] $Fheroes2Source = 'F:\code\fheroes2\src\fheroes2\maps\map_object_info.cpp',

    [Parameter(Mandatory = $false)]
    [string] $Output = (Join-Path $PSScriptRoot '../../src/FHeroes2.Game/Maps/MapObjectCatalog.Roads.cs')
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $Fheroes2Source)) {
    throw "The fheroes2 source file '$Fheroes2Source' does not exist."
}

$lines = Get-Content -LiteralPath $Fheroes2Source

$startLine = -1
$endLine = -1

for ($i = 0; $i -lt $lines.Count; ++$i) {
    if ($startLine -lt 0 -and $lines[$i] -match '^\s*void populateRoads\(') {
        $startLine = $i
        continue
    }

    if ($startLine -ge 0 -and $lines[$i] -match '^\s*void populateStreams\(') {
        $endLine = $i - 1
        break
    }
}

if ($startLine -lt 0 -or $endLine -lt 0) {
    throw "Could not locate populateRoads() in '$Fheroes2Source'."
}

$body = New-Object 'System.Collections.Generic.List[string]'
$partCount = 0
$copyCount = 0
$inLoop = $false

foreach ($raw in $lines[($startLine + 1)..$endLine]) {
    $line = $raw.Trim()

    if ([string]::IsNullOrEmpty($line)) {
        continue
    }

    if ($line -eq '{') {
        continue
    }

    if ($line -eq '}') {
        if ($inLoop) {
            $body.Add('        }')
            $inLoop = $false
            continue
        }

        break
    }

    $indent = if ($inLoop) { '            ' } else { '        ' }

    if ($line.StartsWith('//')) {
        $body.Add($indent + $line)
        continue
    }

    if ($line -match '^assert\(') {
        continue
    }

    if ($line -match '^objects\.resize\(\s*513') {
        $body.Add($indent + 'for (int i = 0; i < 513; ++i) { objects.Add(new ObjectInfo(Mp2ObjectType.None)); }')
        continue
    }

    if ($line -match '^for \( size_t (?<var>\w+) = (?<from>\d+); (?<same>\w+) < (?<to>\d+); \+\+(?<again>\w+) \) \{$') {
        $var = $Matches['var']
        $body.Add("${indent}for (int $var = $($Matches['from']); $var < $($Matches['to']); ++$var)")
        $body.Add("$indent{")
        $inLoop = $true
        continue
    }

    if ($line -match '^objects\[(?<index>.+?)\]\.groundLevelParts\.emplace_back\(\s*MP2::OBJ_ICN_TYPE_ROAD,\s*(?<icn>\d+)U?,\s*fheroes2::Point\{\s*(?<x>-?\d+),\s*(?<y>-?\d+)\s*\},\s*MP2::OBJ_NONE,\s*Maps::TERRAIN_LAYER\s*\);$') {
        $body.Add("${indent}objects[$($Matches['index'])].AddGroundPart(Mp2ObjectIcnType.Road, $($Matches['icn']), new Point($($Matches['x']), $($Matches['y'])), Mp2ObjectType.None, ObjectLayerType.Terrain);")
        ++$partCount
        continue
    }

    if ($line -match '^objects\[(?<left>.+?)\] = objects\[(?<right>.+?)\];$') {
        $body.Add("${indent}objects[$($Matches['left'])] = objects[$($Matches['right'])].Copy();")
        ++$copyCount
        continue
    }

    throw "Unhandled statement in populateRoads(): $line"
}

$header = @(
    'using FHeroes2.Assets.Maps;'
    'using FHeroes2.Core.Geometry;'
    ''
    'namespace FHeroes2.Game.Maps;'
    ''
    '/// <summary>'
    '/// The road table, <c>populateRoads</c> of the reference'
    '/// (<c>参考：src/fheroes2/maps/map_object_info.cpp:48</c>).'
    '///'
    '/// <para>'
    '/// The first 512 objects are the direction layouts of a road, indexed by a nine bit mask that marks'
    '/// which of the eight neighbours are connected; 512 is the entrance road of a castle. The file is'
    '/// generated by <c>tools/scripts/GenerateObjectTables.ps1</c> and must not be edited by hand: every'
    '/// line below is one line of the reference, in the same order, and the order is part of the map'
    '/// format.'
    '/// </para>'
    '/// </summary>'
    'public static partial class MapObjectCatalog'
    '{'
    '    /// <summary>'
    '    /// Fills the road group, <c>populateRoads</c>.'
    '    /// </summary>'
    '    /// <param name="objects">Table of the road group, must be empty.</param>'
    '    private static void PopulateRoads(List<ObjectInfo> objects)'
    '    {'
)

$footer = @(
    '    }'
    '}'
)

$result = New-Object 'System.Collections.Generic.List[string]'

foreach ($item in $header) { $result.Add($item) }
foreach ($item in $body) { $result.Add($item) }
foreach ($item in $footer) { $result.Add($item) }

Set-Content -LiteralPath $Output -Value $result -Encoding utf8

Write-Output "Wrote $($result.Count) lines to '$Output' ($partCount parts, $copyCount copies)."
