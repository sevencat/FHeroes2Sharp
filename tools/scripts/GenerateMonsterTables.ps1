<#
.SYNOPSIS
    Regenerates the table that maps a monster to its FRM archive entry, src/fheroes2/monster/monster_info.cpp's
    binFileName array.

.DESCRIPTION
    The reference keeps the BIN file name in the monster's data row; the port's monster data is hand written
    per creature in several files, and a seventy three row string table is exactly the kind of thing that goes
    wrong silently, so it is read from the reference instead.

    The port's enumeration order is the reference's order, so the table is emitted as an array indexed by
    MonsterType and every row carries the member it belongs to. The two are cross checked by count, and
    MonsterAnimInfoTests pins a few names, because a shift of one would still produce a valid array of the
    same length.

.EXAMPLE
    pwsh tools/scripts/GenerateMonsterTables.ps1
#>
param(
    [Parameter(Mandatory = $false)]
    [string] $MonsterInfoSource = 'F:\code\fheroes2\src\fheroes2\monster\monster_info.cpp',

    [Parameter(Mandatory = $false)]
    [string] $MonsterTypeSource = (Join-Path $PSScriptRoot '../../src/FHeroes2.Game/Monsters/MonsterType.cs'),

    [Parameter(Mandatory = $false)]
    [string] $Output = (Join-Path $PSScriptRoot '../../src/FHeroes2.Game/Monsters/MonsterBinFileNames.cs')
)

$ErrorActionPreference = 'Stop'

# The enumeration: '    Peasant,' or '    Unknown = 0,' inside the enum body, up to MONSTER_COUNT.
# MONSTER_COUNT is the sentinel the reference sizes its array with, not a monster, so it is read as the
# expected length instead of becoming a row.
$members = New-Object 'System.Collections.Generic.List[string]'
$monsterCount = -1
$inEnum = $false
foreach ($line in Get-Content -LiteralPath $MonsterTypeSource) {
    if ($line -match '^\s*public enum MonsterType') {
        $inEnum = $true
        continue
    }

    if (-not $inEnum) {
        continue
    }

    if ($line -match '^\s*\}') {
        break
    }

    if ($line -match '^\s*([A-Za-z][A-Za-z0-9]*)\s*(?:=\s*(\d+))?\s*,') {
        if ($Matches[1] -eq 'MonsterCount') {
            $monsterCount = if ($Matches[2]) { [int]$Matches[2] } else { $members.Count }
            break
        }

        $members.Add($Matches[1])
    }
}

if ($members.Count -eq 0) {
    throw "No members were read from '$MonsterTypeSource'."
}

if ($monsterCount -ne $members.Count) {
    throw "MonsterCount is $monsterCount but $($members.Count) monsters were read from '$MonsterTypeSource'."
}

# The table: 'const char * binFileName[Monster::MONSTER_COUNT] = { "UNKNOWN", ... };'
$names = New-Object 'System.Collections.Generic.List[string]'
$declaration = -1
$lines = Get-Content -LiteralPath $MonsterInfoSource
for ($i = 0; $i -lt $lines.Count; ++$i) {
    if ($lines[$i] -match 'binFileName\[Monster::MONSTER_COUNT\]') {
        $declaration = $i
        break
    }
}

if ($declaration -lt 0) {
    throw "Could not locate binFileName in '$MonsterInfoSource'."
}

for ($i = $declaration; $i -lt $lines.Count; ++$i) {
    foreach ($match in [regex]::Matches($lines[$i], '"([^"]+)"')) {
        $names.Add($match.Groups[1].Value)
    }

    if ($lines[$i] -match '^\s*[^/]*\}\s*;') {
        break
    }
}

# The reference's array is complete: MONSTER_COUNT initialisers, the five random monsters included, all of
# them "UNKNOWN". A mismatched count means either the reference grew or the parsing slipped, so both
# directions are rejected instead of silently padding or truncating.
if ($names.Count -ne $members.Count) {
    throw "binFileName has $($names.Count) entries but MonsterType has $($members.Count) monsters."
}

$file = New-Object 'System.Collections.Generic.List[string]'
$file.Add('namespace FHeroes2.Game.Monsters;')
$file.Add('')
$file.Add('/// <summary>')
$file.Add('/// The FRM archive entry of every monster, the <c>binFileName</c> array of')
$file.Add('/// <c>src/fheroes2/monster/monster_info.cpp:146</c>, indexed by <see cref="MonsterType"/>.')
$file.Add('/// </summary>')
$file.Add('/// <remarks>')
$file.Add('/// <para>')
$file.Add('/// An upgrade usually shares the file of its base creature (<c>ARCHRFRM.BIN</c> three times, for the')
$file.Add('/// Archer and the Ranger) — the animation info then differs only by speed, which is why')
$file.Add('/// <c>MonsterAnimInfo</c> scales it. The five random monsters and the unknown one have no file:')
$file.Add('/// <c>UNKNOWN</c>, which no archive holds.')
$file.Add('/// </para>')
$file.Add('/// <para>Generated by <c>tools/scripts/GenerateMonsterTables.ps1</c>; do not edit by hand.</para>')
$file.Add('/// </remarks>')
$file.Add('internal static class MonsterBinFileNames')
$file.Add('{')
$file.Add('    /// <summary>Entry names, in <see cref="MonsterType"/> order.</summary>')
$file.Add('    internal static readonly string[] ById =')
$file.Add('    [')
for ($i = 0; $i -lt $names.Count; ++$i) {
    $file.Add("        `"$($names[$i])`", // $($members[$i])")
}
$file.Add('    ];')
$file.Add('}')

Set-Content -LiteralPath $Output -Value $file -Encoding utf8NoBOM
Write-Host "Wrote $Output ($($names.Count) entries)"
